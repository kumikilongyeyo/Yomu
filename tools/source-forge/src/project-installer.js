import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here=path.dirname(fileURLToPath(import.meta.url));
const defaultProjectRoot=path.resolve(here,'../../..');

async function exists(p){try{await fs.access(p);return true}catch{return false}}
async function readJson(p){return JSON.parse(await fs.readFile(p,'utf8'))}
async function atomicWrite(p,data){await fs.mkdir(path.dirname(p),{recursive:true});const tmp=`${p}.tmp-${process.pid}-${Date.now()}`;await fs.writeFile(tmp,data);await fs.rename(tmp,p)}

function safeId(raw){const id=String(raw||'').trim().toLowerCase();if(!/^[a-z0-9][a-z0-9._-]{1,48}$/.test(id))throw new Error('Unsafe source id');return id}

function entryFor(descriptor, baseEntry) {
  return {...baseEntry,id:descriptor.id,name:descriptor.name,version:descriptor.version,language:descriptor.language||'en',content:descriptor.content||['manga'],module:`sources/${descriptor.id}.json`,hosts:descriptor.hosts};
}

export async function projectInfo(root=process.env.YOMU_PROJECT_ROOT||defaultProjectRoot){
  root=path.resolve(root);
  const indexPath=path.join(root,'extensions','index.json');
  const standalone=path.resolve(root,'..','yomu-extensions-repo');
  return {root,indexPath,standalone:(await exists(path.join(standalone,'index.json')))?standalone:null};
}

export async function installIntoProject(descriptorInput, entryInput, options={}) {
  const info=await projectInfo(options.projectRoot);
  const id=safeId(descriptorInput.id);
  const index=await readJson(info.indexPath);
  if(!Array.isArray(index.extensions)) throw new Error('Yomu extensions/index.json is malformed');
  const old=index.extensions.find(x=>x.id===id);
  const version=Math.max(Number(descriptorInput.version)||1,(old?.version||0)+1);
  const descriptor={...descriptorInput,id,version};
  const entry=entryFor(descriptor,{...entryInput,version});
  const next=index.extensions.filter(x=>x.id!==id);
  next.push(entry);
  next.sort((a,b)=>String(a.name||a.id).localeCompare(String(b.name||b.id)));
  const nextIndex={...index,updatedAt:new Date().toISOString(),extensions:next};

  const descriptorPath=path.join(info.root,'extensions','sources',`${id}.json`);
  await atomicWrite(descriptorPath,JSON.stringify(descriptor,null,2)+'\n');
  await atomicWrite(info.indexPath,JSON.stringify(nextIndex,null,2)+'\n');
  await rebuildBundled(info.root,nextIndex);

  const synced=[];
  if(options.syncStandalone!==false && info.standalone){
    await atomicWrite(path.join(info.standalone,'sources',`${id}.json`),JSON.stringify(descriptor,null,2)+'\n');
    await atomicWrite(path.join(info.standalone,'index.json'),JSON.stringify(nextIndex,null,2)+'\n');
    const schemaSrc=path.join(info.root,'extensions','schema','extension.schema.json');
    const schemaDst=path.join(info.standalone,'schema','extension.schema.json');
    if(await exists(schemaSrc)) await atomicWrite(schemaDst,await fs.readFile(schemaSrc));
    synced.push(info.standalone);
  }
  return {ok:true,id,version,descriptor,entry,index:nextIndex,projectRoot:info.root,descriptorPath,synced};
}

export async function rebuildBundled(root,index=null){
  root=path.resolve(root);
  index=index||await readJson(path.join(root,'extensions','index.json'));
  const entries=(index.extensions||[]).filter(x=>!x.disabled);
  const names=entries.map((e,i)=>({e,varName:`source${i}`}));
  const lines=[
    '/**',
    ' * Adapters compiled into the Worker.',
    ' * AUTO-GENERATED by tools/source-forge. Edit extensions/index.json or use',
    ' * the Forge installer instead of hand-editing this import table.',
    ' */',
    ...names.map(({e,varName})=>`import ${varName} from '../../extensions/${e.module}';`),
    '',
    'export const BUNDLED_DESCRIPTORS: Record<string, unknown> = {',
    ...names.map(({e,varName})=>`  ${JSON.stringify(e.id)}: ${varName},`),
    '};',''
  ];
  await atomicWrite(path.join(root,'worker','extensions','bundled.ts'),lines.join('\n'));
}
